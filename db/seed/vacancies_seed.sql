numbered_roles AS (
    SELECT *, row_number() OVER () AS rn, count(*) OVER () AS total FROM roles
),
numbered_jd AS (
    SELECT id, row_number() OVER (ORDER BY id) AS rn, count(*) OVER () AS total FROM job_directions
),
generated AS (
    SELECT
        jd.id AS jd_id,
        r.role,
        r.description,
        r.required_exp,
        r.pay_min,
        r.pay_max,
        r.skills,
        g.i
    FROM generate_series(1, :vacancies_count) AS g(i)
    JOIN numbered_roles r ON r.rn = (g.i - 1) % r.total + 1
    JOIN numbered_jd  jd ON jd.rn = (g.i - 1) % jd.total + 1
)
INSERT INTO vacancies (jd, name, description, required_exp, pay_day, skills, created_at, updated_at)
SELECT
    jd_id,
    -- (jd, name) уникальны, поэтому со второго круга ролей добавляем номер
    CASE WHEN i <= (SELECT count(*) FROM numbered_roles)
         THEN role
         ELSE role || ' №' || ((i - 1) / (SELECT count(*) FROM numbered_roles) + 1)
    END,
    description,
    required_exp,
    -- шаг 5 000 ₽ внутри вилки, детерминированно от порядкового номера
    (pay_min + ((i * 7) % ((pay_max - pay_min) / 5000 + 1)) * 5000)::numeric(10,2),
    skills,
    now() - ((i % 90) || ' days')::interval,
    now() - ((i % 30) || ' days')::interval
FROM generated
ON CONFLICT ON CONSTRAINT jd_name_vacancy_unique DO NOTHING;

